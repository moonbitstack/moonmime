#!/usr/bin/env python3
# Turn the Web Platform Tests MIME type data into MoonBit test vectors.
#
# The data under scripts/wpt/mimesniff/ is a pinned copy of the suite's own
# JSON, so this runs offline and produces the same bytes on every machine.
# `--check` regenerates in memory and fails when a committed vector file is out
# of date; CI runs it, so a stale vector file cannot be merged.
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DATA = ROOT / "scripts" / "wpt" / "mimesniff"
PIN = DATA / "pin.json"

# One function per few hundred cases: a single array literal of a thousand
# entries overflows the initialiser of a wasm module.
BATCH = 200

# (source file, MoonBit file, function prefix, doc line)
OUTPUTS = [
    ("mime-types.json", "wpt_mime_types_test.mbt", "wpt_mime_types", "mime-types.json"),
    (
        "generated-mime-types.json",
        "wpt_generated_mime_types_test.mbt",
        "wpt_generated_mime_types",
        "generated-mime-types.json",
    ),
]

HEADER = """\
// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by scripts/gen_wpt_vectors.py from the Web Platform Tests suite,
// mimesniff/mime-types/resources/{source} at commit
// {commit}.
// Do not edit: change the data under scripts/wpt/mimesniff/ and run the
// generator, which keeps this file and the suite in step.
"""


def blob_id(data):
    """The git object id of a file's bytes, the same id the pin records."""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def load(pin):
    files = {}
    for entry in pin["files"]:
        path = DATA / entry["local"]
        raw = path.read_bytes()
        found = blob_id(raw)
        if found != entry["blob"]:
            raise SystemExit(
                f"{path.relative_to(ROOT)}: git blob {found}, pin says {entry['blob']}"
            )
        files[entry["local"]] = json.loads(raw.decode("utf-8"))
    return files


def mb_string(text):
    """A MoonBit literal; outside printable ASCII everything is escaped, so the
    source stays one encoding and control characters stay visible."""
    out = ['"']
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= code <= 0x7E:
            out.append(ch)
        else:
            out.append("\\u{%04x}" % code)
    out.append('"')
    return "".join(out)


def cases_of(entries):
    """(input, expected) for every object; the arrays' string items are prose."""
    return [
        (entry["input"], entry["output"])
        for entry in entries
        if not isinstance(entry, str)
    ]


def case_lines(text, expected):
    """One case as the formatter would lay it out: on one line while it fits in
    the margin, split over four when it does not, and a `Some` whose string
    alone overflows split again. Emitting the wrapped forms here is what keeps
    `moon fmt` from rewriting the generated files."""
    want = "None" if expected is None else f"Some({mb_string(expected)})"
    one = f"    ({mb_string(text)}, {want}),"
    if len(one) <= 81:
        return [one]
    if len(f"      {want},") <= 81:
        return ["    (", f"      {mb_string(text)},", f"      {want},", "    ),"]
    return [
        "    (",
        f"      {mb_string(text)},",
        "      Some(",
        f"        {mb_string(expected)},",
        "      ),",
        "    ),",
    ]


def render(data_file, module_file, prefix, source, pin):
    entries = load(pin)[data_file]
    cases = cases_of(entries)
    out = [HEADER.format(source=source, commit=pin["commit"]).rstrip("\n")]
    batches = [cases[i : i + BATCH] for i in range(0, len(cases), BATCH)]
    for number, batch in enumerate(batches, start=1):
        out.append("")
        out.append("///|")
        out.append(f"fn {prefix}_{number}() -> Array[(String, String?)] {{")
        out.append("  [")
        for text, expected in batch:
            out.extend(case_lines(text, expected))
        out.append("  ]")
        out.append("}")
    out.append("")
    out.append("///|")
    out.append(f"fn {prefix}_cases() -> Array[(String, String?)] {{")
    out.append("  let out : Array[(String, String?)] = []")
    for number in range(1, len(batches) + 1):
        out.append(f"  out.append({prefix}_{number}()[:])")
    out.append("  out")
    out.append("}")
    return module_file, "\n".join(out) + "\n", len(cases)


def main(argv):
    check = "--check" in argv
    pin = json.loads(PIN.read_text(encoding="utf-8"))
    stale = []
    for data_file, module_file, prefix, source in OUTPUTS:
        name, text, count = render(data_file, module_file, prefix, source, pin)
        path = ROOT / "src" / name
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                stale.append(name)
            print(f"{name}: {count} cases")
            continue
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print(f"wrote src/{name}: {count} cases")
    if stale:
        print("out of date: " + ", ".join(stale), file=sys.stderr)
        print("run scripts/gen_wpt_vectors.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
